# Convenience: normalize a raw role string to a small set of high-level buckets
# useful for entity-network analysis (buyer/seller vs lender vs neutral/other).
def role_bucket(role):
    if role is None:
        return "N/A"
    r = role.upper()
    if any(k in r for k in ["GRANTOR", "SELLER", "MORTGAGOR", "BORROWER", "DEBTOR", "ASSIGNOR", "TRANSFEROR", "LESSOR"]):
        return "SIDE_1 (seller/borrower/debtor/assignor)"
    if any(k in r for k in ["GRANTEE", "BUYER", "MORTGAGEE", "LENDER", "SECURED PARTY", "ASSIGNEE", "BENEFICIARY", "LESSEE"]):
        return "SIDE_2 (buyer/lender/secured-party/assignee)"
    return "OTHER/GENERIC"
